// Slovak plural rule for "zmena" (change): 1 = zmena, 2–4 = zmeny, 5+ = zmien.
function nameChangeWord(count: number): string {
  if (count === 1) return "zmena";
  if (count >= 2 && count <= 4) return "zmeny";
  return "zmien";
}

